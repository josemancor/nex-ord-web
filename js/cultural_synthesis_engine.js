    // Interacción MouseMove y Detección de Hover
    function handlePCAMouseMove(e) {
        if (!activePCACanvas) return;
        const rect = activePCACanvas.getBoundingClientRect();
        const mx = e.clientX - rect.left;
        const my = e.clientY - rect.top;

        const w = activePCACanvas.width / (window.devicePixelRatio || 1);
        const h = activePCACanvas.height / (window.devicePixelRatio || 1);
        const pad = 65;
        const minX = -2.2, maxX = 2.2, minY = -1.8, maxY = 1.8;

        function toX(vx) { return pad + ((vx - minX) / (maxX - minX)) * (w - 2 * pad); }
        function toY(vy) { return h - pad - ((vy - minY) / (maxY - minY)) * (h - 2 * pad); }

        const sData = CULTURAL_SYNTHESIS_DATA[activePCAWorkKey] || CULTURAL_SYNTHESIS_DATA["clara"];
        let found = null;

        // 1. Probar Baricentros
        if (sData.characters) {
            for (let c of sData.characters) {
                const dist = Math.hypot(toX(c.bx) - mx, toY(c.by) - my);
                if (dist < 14) {
                    found = { type: 'baricentro', data: c, mx: e.clientX, my: e.clientY };
                    break;
                }
            }
        }

        // 2. Probar Puntos TC
        if (!found && sData.puntos_tc) {
            for (let pt of sData.puntos_tc) {
                if (activePCAFilterCharId && activePCAFilterCharId !== pt.charId) continue;
                const dist = Math.hypot(toX(pt.x) - mx, toY(pt.y) - my);
                if (dist < 10) {
                    found = { type: 'point', data: pt, mx: e.clientX, my: e.clientY };
                    break;
                }
            }
        }

        // 3. Probar Vectores AAG
        if (!found && sData.aag_vectors) {
            for (let v of sData.aag_vectors) {
                const dist = Math.hypot(toX(v.x) - mx, toY(v.y) - my);
                if (dist < 12) {
                    found = { type: 'aag', data: v, mx: e.clientX, my: e.clientY };
                    break;
                }
            }
        }

        pcaHoverItem = found;
        if (found) {
            activePCACanvas.style.cursor = 'pointer';
            showPCATooltip(found);
        } else {
            activePCACanvas.style.cursor = 'default';
            hidePCATooltip();
        }
        renderPCAPointillistCloud();
    }

