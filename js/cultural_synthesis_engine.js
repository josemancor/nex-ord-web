        const partners = sData.characters.filter(c => c.id !== charDef.id);
        const N = partners.length;
        const cx = w / 2;
        const cy = h / 2 + 10;
        const maxR = Math.min(cx, cy) - 50;

        // Anillos Radiales Concéntricos
        const rings = [0.25, 0.50, 0.75, 1.0];
        ctx.strokeStyle = 'rgba(255, 255, 255, 0.08)';
        ctx.lineWidth = 1;
