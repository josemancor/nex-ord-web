    function renderPCAPointillistCloud() {
        if (!activePCACanvas) return;
        const canvas = activePCACanvas;
        const ctx = canvas.getContext('2d');
        const container = canvas.parentElement;
        if (!container) return;

        const w = container.clientWidth || 900;
        const h = Math.max(container.clientHeight || 620, 540);

        const dpr = window.devicePixelRatio || 1;
        canvas.width = w * dpr;
        canvas.height = h * dpr;
        canvas.style.width = w + 'px';
        canvas.style.height = h + 'px';

        ctx.resetTransform();
        ctx.scale(dpr, dpr);

        const sData = CULTURAL_SYNTHESIS_DATA[activePCAWorkKey] || CULTURAL_SYNTHESIS_DATA["clara"];

        // 1. Fondo Canón 8: Azul Marino Oscuro #0B132B
        ctx.fillStyle = '#0B132B';
        ctx.fillRect(0, 0, w, h);

        // Bounding Box con márgenes holgados
        let minX = -2.2, maxX = 2.2, minY = -1.8, maxY = 1.8;
        const pad = 65;

        // Escalamiento Cartesiano
        function toX(vx) {
            return pad + ((vx - minX) / (maxX - minX)) * (w - 2 * pad);
        }
        function toY(vy) {
            // Invertir Y para coordenadas cartesianas (arriba positivo)
            return h - pad - ((vy - minY) / (maxY - minY)) * (h - 2 * pad);
        }

        // 2. Rejilla y Ejes Cartesianos Ortogonales
        ctx.strokeStyle = 'rgba(255, 255, 255, 0.05)';
        ctx.lineWidth = 1;
        for (let gx = -2.0; gx <= 2.0; gx += 0.5) {
            ctx.beginPath();
            ctx.moveTo(toX(gx), toY(minY));
            ctx.lineTo(toX(gx), toY(maxY));
            ctx.stroke();
        }
        for (let gy = -1.5; gy <= 1.5; gy += 0.5) {
            ctx.beginPath();
            ctx.moveTo(toX(minX), toY(gy));
            ctx.lineTo(toX(maxX), toY(gy));
            ctx.stroke();
        }

        // Eje X (F1) y Eje Y (F2) ortogonales
        ctx.strokeStyle = 'rgba(0, 245, 212, 0.45)';
        ctx.lineWidth = 1.5;

        // Eje X
        ctx.beginPath();
        ctx.moveTo(toX(minX), toY(0));
        ctx.lineTo(toX(maxX), toY(0));
        ctx.stroke();

        // Eje Y
        ctx.beginPath();
        ctx.moveTo(toX(0), toY(minY));
        ctx.lineTo(toX(0), toY(maxY));
        ctx.stroke();

        // Etiquetas de los Ejes
        ctx.font = 'bold 11px "Roboto Mono", monospace';
        ctx.fillStyle = '#00F5D4';
        ctx.textAlign = 'right';
        ctx.fillText(sData.inercias.f1_label, toX(maxX) - 10, toY(0) - 10);
        ctx.textAlign = 'center';
        ctx.fillText(sData.inercias.f2_label, toX(0) + 12, toY(maxY) + 14);

        // 3. Isobaras Termográficas KDE de atenuación sutil (alpha = 0.18)
        if (activePCALayers.kde) {
            drawKDEIsobars(ctx, sData, toX, toY);
        }

        // 4. Trayectorias Geodésicas / Órbitas Longitudinales T1 -> Tk
        if (activePCALayers.orbits && sData.puntos_tc) {
            drawCharacterOrbits(ctx, sData, toX, toY);
        }

        // 5. Nubes Puntillistas de Micro-Píxeles Puros Sin Contorno (Canón 8: sigma = 0.032, edgecolors='none')
        if (activePCALayers.pointillism && sData.puntos_tc) {
            drawPointillistClouds(ctx, sData, toX, toY);
        }

        // 6. Vectores Suplementarios AAG y VAR
        if (activePCALayers.aag && sData.aag_vectors) {
            drawAAGVectors(ctx, sData, toX, toY);
        }

        // 7. Baricentros Identitarios Bi (Centroides Gravitatorios)
        if (activePCALayers.baricentros && sData.characters) {
            drawBaricentros(ctx, sData, toX, toY);
        }

        // 8. Leyenda Mínima Interior (Canón 8: loc='upper right')
        drawRule8Legend(ctx, w);
    }

    // Dibujo de Isobaras KDE (Canón 8)
    function drawKDEIsobars(ctx, sData, toX, toY) {
        ctx.save();
        const clusters = [
            { x: 1.1, y: 0.45, rx: 110, ry: 80, col: 'rgba(0, 255, 135, 0.18)' },
            { x: -1.3, y: -0.65, rx: 90, ry: 70, col: 'rgba(255, 0, 127, 0.18)' },
            { x: 0.5, y: -0.4, rx: 80, ry: 60, col: 'rgba(255, 159, 28, 0.14)' }
        ];

        clusters.forEach(c => {
            const cx = toX(c.x);
            const cy = toY(c.y);
            const grad = ctx.createRadialGradient(cx, cy, 10, cx, cy, c.rx);
            grad.addColorStop(0, c.col);
            grad.addColorStop(0.6, c.col.replace('0.18', '0.07').replace('0.14', '0.05'));
            grad.addColorStop(1, 'rgba(11, 19, 43, 0)');

            ctx.fillStyle = grad;
            ctx.beginPath();
            ctx.ellipse(cx, cy, c.rx, c.ry, 0, 0, Math.PI * 2);
            ctx.fill();

            // Línea de isobara delgada
            ctx.strokeStyle = c.col.replace('0.18', '0.28').replace('0.14', '0.22');
            ctx.lineWidth = 1;
            ctx.setLineDash([4, 4]);
            ctx.stroke();
            ctx.setLineDash([]);
        });
        ctx.restore();
    }

    // Dibujo de Órbitas Geodésicas
    function drawCharacterOrbits(ctx, sData, toX, toY) {
        ctx.save();
        const grouped = {};
        sData.puntos_tc.forEach(pt => {
            if (!grouped[pt.charId]) grouped[pt.charId] = [];
            grouped[pt.charId].push(pt);
        });

        Object.keys(grouped).forEach(cId => {
            if (activePCAFilterCharId && activePCAFilterCharId !== cId) return;

            const charDef = sData.characters.find(c => c.id === cId) || { color: '#94A3B8' };
            const pts = grouped[cId];
            if (pts.length < 2) return;

            ctx.beginPath();
            ctx.moveTo(toX(pts[0].x), toY(pts[0].y));
            for (let i = 1; i < pts.length; i++) {
                ctx.lineTo(toX(pts[i].x), toY(pts[i].y));
            }

            const isFocus = (activePCAFilterCharId === cId);
            ctx.strokeStyle = isFocus ? charDef.color : hexToRgba(charDef.color, 0.28);
            ctx.lineWidth = isFocus ? 2.5 : 1.2;
            ctx.setLineDash([4, 3]);
            ctx.stroke();
            ctx.setLineDash([]);
        });
        ctx.restore();
    }

    // Dibujo de Nubes Puntillistas (Canón 8: micro-píxeles puros sin contorno sigma=0.032)
    function drawPointillistClouds(ctx, sData, toX, toY) {
        ctx.save();
        const valenceColors = {
            'Ee': '#00FF87',       // Verde Neón: Elección Mútua / Predominante
            'Rr': '#FF007F',       // Rosa Neón: Rechazo Mútuo / Conflicto
            'Er': '#FF9F1C',       // Naranja Neón: Oposición de Sentimientos
            'neutral': '#FFE600'   // Amarillo Dorado: Indiferencia / Neutralidad
        };

        sData.puntos_tc.forEach((pt, idx) => {
            if (activePCAFilterCharId && activePCAFilterCharId !== pt.charId) return;

            const px = toX(pt.x);
            const py = toY(pt.y);
            const baseCol = valenceColors[pt.valence] || '#FFE600';

            // Generador pseudo-aleatorio estable basado en índice
            const dotCount = 28;
            const sigmaPx = 14; // Representación de sigma = 0.032 en espacio de píxeles

            ctx.fillStyle = hexToRgba(baseCol, 0.45);
            for (let d = 0; d < dotCount; d++) {
                // Distribución gaussiana aproximada (Box-Muller simplificado)
                const u1 = Math.sin(idx * 37 + d * 13) * 0.5 + 0.5;
                const u2 = Math.cos(idx * 23 + d * 19) * 0.5 + 0.5;
                const radius = Math.sqrt(-2 * Math.log(Math.max(u1, 0.001))) * sigmaPx;
                const theta = 2 * Math.PI * u2;
                const dx = radius * Math.cos(theta);
                const dy = radius * Math.sin(theta);

                ctx.beginPath();
                ctx.arc(px + dx, py + dy, 1.6, 0, Math.PI * 2);
                ctx.fill(); // Sin borde: edgecolors='none' Canón 8
            }

            // Núcleo central del punto TC
            ctx.fillStyle = baseCol;
            ctx.beginPath();
            ctx.arc(px, py, 3.5, 0, Math.PI * 2);
            ctx.fill();

            // Anillo blanco si está hovered
            if (pcaHoverItem && pcaHoverItem.type === 'point' && pcaHoverItem.data === pt) {
                ctx.strokeStyle = '#FFFFFF';
                ctx.lineWidth = 2;
                ctx.beginPath();
                ctx.arc(px, py, 6.5, 0, Math.PI * 2);
                ctx.stroke();
            }
        });
        ctx.restore();
    }

